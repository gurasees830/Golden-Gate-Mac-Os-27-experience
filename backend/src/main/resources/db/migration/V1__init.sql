-- Golden Gate Cloud schema (portable between PostgreSQL and H2 for tests)
CREATE TABLE user_account (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(254) NOT NULL UNIQUE, -- stored lower-cased by the API
    display_name  VARCHAR(80)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE user_preferences (
    user_id    BIGINT PRIMARY KEY REFERENCES user_account (id) ON DELETE CASCADE,
    data       TEXT NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version    BIGINT NOT NULL DEFAULT 0
);
